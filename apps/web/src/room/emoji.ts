const ALL = EMOJI_GROUPS.flatMap((g) => g.emojis);

/** The emojis a search finds: each word of it starts a word of their names. At most `limit`, in the picker's order. */
export function findEmojis(query: string, limit = 48): Emoji[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return ALL.filter((e) => {
    const names = e.name.split(' ');
    return words.every((w) => names.some((n) => n.startsWith(w)));
  }).slice(0, limit);
}
